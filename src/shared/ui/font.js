const GLYPHS = {};
for (const [ch, rows] of Object.entries(G)) {
  GLYPHS[ch] = { w: rows[0].length, rows: rows.map((r) => [...r].map((b) => b === '#')) };
}
GLYPHS[' '] = { w: 2, rows: [] };

export const GLYPH_H = 6; // cap height
export const LINE_H = 10;

function glyph(ch) {
  return GLYPHS[ch] ?? GLYPHS[ch.toUpperCase()] ?? GLYPHS['?'];
}

export function textWidth(text, scale = 1) {
  let w = 0;
  for (const ch of String(text)) w += glyph(ch).w + 1;
  return Math.max(0, w - 1) * scale;
}

const BAYER = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5];

/**
 * Draw text with the top of its capitals at (x, y). Coordinates are whole UI pixels.
 * `reveal` (0..1) draws only part of the pixels in an ordered-dither pattern, so text can
 * fade in or out while staying on the pixel grid.
 */
export function drawText(ctx, text, x, y, color, { scale = 1, shadow = null, reveal = 1 } = {}) {
  x = Math.round(x);
  y = Math.round(y);
  if (shadow) drawText(ctx, text, x + scale, y + scale, shadow, { scale, reveal });
  ctx.fillStyle = color;
  let cx = x;
  const cut = reveal * 16;
  for (const ch of String(text)) {
    const g = glyph(ch);
    g.rows.forEach((row, r) => {
      row.forEach((on, c) => {
        if (!on) return;
        const px = cx + c * scale, py = y + r * scale;
        if (cut < 16 && BAYER[((py / scale) & 3) * 4 + ((px / scale) & 3)] >= cut) return;
        ctx.fillRect(px, py, scale, scale);
      });
    });
    cx += (g.w + 1) * scale;
  }
  return cx - x;
}

export function drawTextCentered(ctx, text, cx, y, color, opts = {}) {
  const w = textWidth(text, opts.scale ?? 1);
  return drawText(ctx, text, Math.round(cx - w / 2), y, color, opts);
}

/** Greedy word wrap to a pixel width. */
export function wrapText(text, maxWidth, scale = 1) {
  const lines = [];
  for (const para of String(text).split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const next = line ? `${line} ${word}` : word;
      if (textWidth(next, scale) <= maxWidth) line = next;
      else {
        if (line) lines.push(line);
        line = word;
      }
    }
    lines.push(line);
  }
  return lines;
}
